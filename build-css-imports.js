// scripts/build-css-imports.js
const fs = require('fs');
const path = require('path');

const APP_DIR = path.join(__dirname, './app');
const OUTPUT_FILE = path.join(APP_DIR, 'styles/imports.css');

function walk(dir, fileList = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(fullPath, fileList);
    }
     else if (
      /\.css$/.test(entry.name) &&
      !/\.module\.css$/.test(entry.name) && // skip CSS Modules
      !/globals\.css$/.test(entry.name) && // skip globals.css
      !/imports\.css$/.test(entry.name) && // skip imports.css
      fullPath !== OUTPUT_FILE
    ) {
      fileList.push(fullPath);
    }
  }
  return fileList;
}

function generate() {
  const files = walk(APP_DIR).sort();

  let output = `/* AUTO-GENERATED by scripts/build-css-imports.js — do not edit directly */\n\n`;
  for (const file of files) {
    const importPath = path.relative(APP_DIR, file).replace(/\\/g, '/');
    output += `@import '../${importPath}';\n`;
  }

  fs.writeFileSync(OUTPUT_FILE, output);
  console.log(`✓ globals.css regenerated (${files.length} files)`);
}


  generate();